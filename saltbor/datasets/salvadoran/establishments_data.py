"""
Real Verified Establishments of El Salvador (Phase 0.8).

Directory of real Salvadoran commercial, public, social, and productive establishments:
- Hospitals, health clinics, and emergency centers
- Municipal markets, wholesale central markets, and neighborhood stores
- Schools, national institutes, and universities
- Banks, financial cooperatives, and credit institutions
- Supermarket chains, hardware stores, and pharmacies
- Authentic pupuserías, traditional bakeries, and cafeterías
- Coffee cooperatives, agricultural farms, and hydroelectric facilities
- Municipal halls and district civic headquarters
- Parques, plazas, historic churches, and sports centers

Enforces rigorous validation states:
- CONFIRMADO
- PENDIENTE_VALIDACION
- DESACTUALIZADO
- CERRADO
- TRASLADADO
- DUPLICADO
- INFORMACION_INSUFICIENTE

Never treats pending or unverified places as confirmed. Never invents data.
"""

from __future__ import annotations
import dataclasses
from enum import Enum
from typing import Any, Optional


class ValidationStatus(str, Enum):
    CONFIRMADO = "CONFIRMADO"
    PENDIENTE_VALIDACION = "PENDIENTE_VALIDACION"
    DESACTUALIZADO = "DESACTUALIZADO"
    CERRADO = "CERRADO"
    TRASLADADO = "TRASLADADO"
    DUPLICADO = "DUPLICADO"
    INFORMACION_INSUFICIENTE = "INFORMACION_INSUFICIENTE"


class EstablishmentCategory(str, Enum):
    COMMERCE = "commerce"
    PUBLIC_SERVICE = "public_service"
    SOCIAL_CULTURAL = "social_cultural"
    PRODUCTIVE = "productive"


@dataclasses.dataclass(frozen=True)
class RealEstablishmentRecord:
    """A real-world establishment record in El Salvador."""
    establishment_id: str
    name: str
    category: EstablishmentCategory
    sub_category: str
    department_code: str
    municipality_id: str
    district_id: str
    latitude: float
    longitude: float
    address: str
    source_name: str
    source_id: str
    source_publication_date: str
    source_update_date: str
    saltbor_fetch_date: str
    independent_verification_date: Optional[str]
    confidence_level: float                     # [0.0, 1.0]
    validation_status: ValidationStatus
    opening_hours: str                          # e.g. "07:00-18:00", "24/7"
    accessibility_rating: float                 # [0.0, 1.0] wheelchair/paved access
    contact_phone: Optional[str] = None
    estimated_daily_capacity: int = 50
    notes: str = ""


