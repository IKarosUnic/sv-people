"""SALTBOR Multi-Agent Orchestration Pydantic v2 Schemas and Contracts.

Defines the structured data models exchanged between Orchestrator, Writer,
Implementation, Research, and Auditor agents.
"""

from enum import Enum
from typing import Any
from pydantic import BaseModel, Field


class AgentRole(str, Enum):
    """Canonical agent roles."""
    ORCHESTRATOR = "orchestrator"
    WRITER = "writer"
    IMPLEMENTATION = "implementation"
    RESEARCH = "research"
    AUDITOR = "auditor"


class ComplexityTier(str, Enum):
    """Complexity tiers mapped to Antigravity model tiers.
    
    Note: 'pro' is excluded due to inferior capability compared to Gemini 3.8 Flash High.
    High and Critical reasoning are executed exclusively on Gemini 3.8 Flash (High)
    (using 'inherit' in Dynamic Workflows or 'gemini-3.8-flash-high' in Swarm).
    """
    LOW = "flash_lite"
    MODERATE = "flash"
    HIGH = "inherit"
    CRITICAL = "gemini-3.8-flash-high"


class AuditStatus(str, Enum):
    """Verdict rendered by the Auditor Agent."""
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    ESCALATED = "ESCALATED"


class TaskSpecification(BaseModel):
    """Specification generated by Writer Agent."""
    spec_title: str = Field(description="Descriptive title of the specification")
    summary: str = Field(description="High level summary of the requirement")
    requirements: list[str] = Field(description="Specific, testable functional requirements")
    acceptance_criteria: list[str] = Field(default_factory=list, description="Explicit verification conditions")


class ImplementationDeliverable(BaseModel):
    """Deliverable generated by Implementation Agent."""
    target_file: str = Field(description="Relative path of the target source file")
    function_code: str = Field(description="Clean, documented production implementation")
    unit_test_code: str = Field(description="Comprehensive pytest unit test suite")
    tests_passed: bool = Field(default=True, description="Whether tests passed in the local sandbox")
    complexity_notes: str = Field(default="", description="Big-O time and space complexity notes")
    fix_summary: str | None = Field(default=None, description="Explanation of fixes made addressing auditor feedback")


class AuditorReport(BaseModel):
    """Review report emitted by Auditor Agent."""
    status: AuditStatus = Field(description="Audit decision: APPROVED, REJECTED, or ESCALATED")
    feedback: str = Field(description="Detailed critique, defect list, or rationale")
    checks_passed: list[str] = Field(default_factory=list, description="Specific checks verified as passing")
    conservation_verified: bool = Field(default=True, description="True if no conservation laws or balance leaks exist")
    security_risks_detected: list[str] = Field(default_factory=list, description="Potential vulnerabilities or leaks")


class WorkflowRunMetrics(BaseModel):
    """Telemetry and resource usage metrics."""
    run_id: str
    total_turns: int = 0
    total_tokens: dict[str, int] = Field(default_factory=dict)
    elapsed_seconds: float = 0.0
    status: str = "COMPLETED"
    remediations_count: int = 0
